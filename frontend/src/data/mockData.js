const referenceDate = new Date()

const dateInMonth = (monthsAgo, day) => {
  const date = new Date(
    referenceDate.getFullYear(),
    referenceDate.getMonth() - monthsAgo,
    1,
  )
  const lastDay = new Date(
    date.getFullYear(),
    date.getMonth() + 1,
    0,
  ).getDate()
  const cappedDay =
    monthsAgo === 0
      ? Math.min(day, referenceDate.getDate())
      : Math.min(day, lastDay)

  date.setDate(Math.max(1, cappedDay))
  return toDateKey(date)
}

